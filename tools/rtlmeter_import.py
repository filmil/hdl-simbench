"""Turns an RTLMeter design descriptor into Bazel test cases.

RTLMeter (https://github.com/verilator/rtlmeter) describes each design in a
descriptor.yaml. This tool reads one and writes cases.bzl beside it: a
Starlark dict with every case (configuration and test) already resolved, the
way RTLMeter's own src/rtlmeter/descriptors.py resolves it:

  - A configuration's compile settings extend the design's: lists are
    concatenated in order, maps are merged with later entries winning,
    scalars take the last value given.
  - A test's settings gather, in order, the design's execute.common, the
    design's test, the configuration's execute.common and the
    configuration's test.
  - The harness __rtlmeter_utils.sv is added to the sources, and
    __rtlmeter_top_include.vh to the include files.
  - mainClock becomes the define __RTLMETER_MAIN_CLOCK.
  - A descriptor without configurations has one, named "default".

Verilator-only arguments are split: "-G<name>=<value>" parameter overrides
go to "params", which every simulator can apply; the rest stay in
"verilator_args", which only Verilator gets.

Usage:
  rtlmeter_import.py <design dir>             writes <design dir>/cases.bzl
  rtlmeter_import.py --check <design dir>     fails if cases.bzl is stale
"""

import os
import sys

import yaml

_HEADER = (
    "# Generated by //tools:rtlmeter_import from descriptor.yaml. Do not edit;\n"
    "# rerun the tool. its cases_test checks it.\n"
)


def _defaults(desc):
    # As RTLMeter's yaml_descriptor._applyDefaults: absent maps become {}.
    desc = dict(desc or {})
    desc["compile"] = desc.get("compile") or {}
    desc["execute"] = dict(desc.get("execute") or {})
    desc["execute"]["common"] = desc["execute"].get("common") or {}
    tests = desc["execute"].get("tests") or {}
    desc["execute"]["tests"] = {k: v or {} for k, v in tests.items()}
    return desc


def _scalar(key, *descs):
    result = None
    for d in descs:
        if d.get(key) is not None:
            result = str(d[key])
    return result


def _list(key, *descs):
    result = []
    for d in descs:
        result.extend(str(x) for x in d.get(key, []) or [])
    return result


def _dict(key, *descs):
    result = {}
    for d in descs:
        result.update((k, str(v)) for k, v in (d.get(key) or {}).items())
    return result


def _split_verilator_args(args):
    params, rest = {}, []
    for a in args:
        if a.startswith("-G") and "=" in a:
            name, value = a[2:].split("=", 1)
            params[name] = value
        else:
            rest.append(a)
    return params, rest


def resolve(desc):
    """Returns {config: {...compile..., "tests": {test: {...}}}}."""
    root = _defaults(desc)
    configs = desc.get("configurations") or {"default": {}}
    out = {}
    for cname, cdesc in configs.items():
        cfg = _defaults(cdesc)
        rc, cc = root["compile"], cfg["compile"]
        top = _scalar("topModule", rc, cc)
        clock = _scalar("mainClock", rc, cc)
        if top is None or clock is None:
            raise ValueError("configuration %s: topModule and mainClock are required" % cname)
        defines = _dict("verilogDefines", rc, cc)
        defines["__RTLMETER_MAIN_CLOCK"] = clock
        params, vargs = _split_verilator_args(_list("verilatorArgs", rc, cc))
        compile_ = {
            "top": top,
            "clock": clock,
            "srcs": _list("verilogSourceFiles", rc, cc),
            "includes": _list("verilogIncludeFiles", rc, cc),
            "defines": defines,
            "params": params,
            "verilator_args": vargs,
            "cpp_srcs": _list("cppSourceFiles", rc, cc),
            "cpp_includes": _list("cppIncludeFiles", rc, cc),
            "cpp_defines": _dict("cppDefines", rc, cc),
        }
        tests = {}
        names = list(root["execute"]["tests"]) + [
            t for t in cfg["execute"]["tests"] if t not in root["execute"]["tests"]
        ]
        for tname in names:
            parts = (
                root["execute"]["common"],
                root["execute"]["tests"].get(tname, {}),
                cfg["execute"]["common"],
                cfg["execute"]["tests"].get(tname, {}),
            )
            cycles = _scalar("expectedCycles", *parts)
            tests[tname] = {
                "args": _list("args", *parts),
                "files": _list("files", *parts),
                "tags": _list("tags", *parts),
                "post_hook": _scalar("postHook", *parts),
                "expected_cycles": int(cycles) if cycles is not None else None,
            }
        compile_["tests"] = tests
        out[cname] = compile_
    return out


def _starlark(value, indent=0):
    pad = "    " * indent
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')
    if isinstance(value, list):
        if not value:
            return "[]"
        items = ["%s    %s,\n" % (pad, _starlark(v, indent + 1)) for v in value]
        return "[\n%s%s]" % ("".join(items), pad)
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [
            "%s    %s: %s,\n" % (pad, _starlark(k), _starlark(v, indent + 1))
            for k, v in value.items()
        ]
        return "{\n%s%s}" % ("".join(items), pad)
    raise TypeError("cannot write %r" % (value,))


def render(design_dir):
    with open(os.path.join(design_dir, "descriptor.yaml"), encoding="utf-8") as f:
        desc = yaml.safe_load(f)
    return "%s\nCASES = %s\n" % (_HEADER, _starlark(resolve(desc)))


def main(argv):
    check = False
    if argv and argv[0] == "--check":
        check, argv = True, argv[1:]
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    # Under "bazel run" the working directory is the runfiles tree; a
    # relative path means the caller's directory.
    design_dir = argv[0]
    if not os.path.isabs(design_dir) and "BUILD_WORKING_DIRECTORY" in os.environ:
        design_dir = os.path.join(os.environ["BUILD_WORKING_DIRECTORY"], design_dir)
    text = render(design_dir)
    target = os.path.join(design_dir, "cases.bzl")
    if check:
        with open(target, encoding="utf-8") as f:
            if f.read() != text:
                print("%s is stale: rerun //tools:rtlmeter_import" % target, file=sys.stderr)
                return 1
        return 0
    with open(target, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
