"""Writes the report's LaTeX tables from //tools:summarize_runs CSV output.

  report_tables --out tables.tex <campaign>=<summary.csv> [...]

Each campaign gets one table per language: SystemVerilog designs, and VHDL
(the design "vhdl"). A cell shows the median of its kept runs with
[minimum-maximum], as summarize_runs computed them; nothing is recomputed
here. Cells that summarize_runs did not report (more runs needed, failing,
cycles differ) are listed with their state and no numbers. A rate marked
resolution-limited gets a dagger. Each campaign also yields the commits and
lockfile hashes its cells ran at, for the methods section.
"""

import argparse
import csv
import sys

LANGUAGES = [("sv", "SystemVerilog"), ("vhdl", "VHDL")]


def tex(s):
    """s with LaTeX's special characters escaped."""
    out = []
    for c in str(s):
        if c in "&%$#_{}":
            out.append("\\" + c)
        elif c == "~":
            out.append("\\textasciitilde{}")
        elif c == "^":
            out.append("\\textasciicircum{}")
        elif c == "\\":
            out.append("\\textbackslash{}")
        else:
            out.append(c)
    return "".join(out)


def language(row):
    return "vhdl" if row["design"] == "vhdl" else "sv"


def num(v, digits):
    """A number with the given decimals, or with three significant digits
    in exponent form when it is 10^5 or more."""
    x = float(v)
    if abs(x) >= 1e5:
        return "%.3g" % x
    return "%.*f" % (digits, x)


def rng(row, key, digits):
    """'median [min-max]' for one metric, or '--' when it is empty."""
    if row.get(key, "") == "":
        return "--"
    return "%s [%s--%s]" % (
        num(row[key], digits),
        num(row[key + "_min"], digits),
        num(row[key + "_max"], digits),
    )


def mib(row):
    """Peak RSS of the run in MiB, median [min-max]."""
    if row.get("run_maxrss_kib", "") == "":
        return "--"
    f = lambda k: "%.0f" % (float(row[k]) / 1024.0)
    return "%s [%s--%s]" % (f("run_maxrss_kib"), f("run_maxrss_kib_min"), f("run_maxrss_kib_max"))


def cell_row(row):
    sim = "%s %s" % (row["simulator"], row["simulator_version"])
    cap = row["max_cycles"] or "--"
    head = [tex(sim), tex(row["design"]), tex(row["case"]), tex(cap)]
    if row["state"] != "ok":
        return head + [
            "\\multicolumn{7}{l}{%s (%s of %s runs kept)}"
            % (tex(row["state"]), tex(row["kept"]), tex(row["runs"]))
        ]
    rate = rng(row, "cycles_per_s", 0)
    if row["resolution_limited"] == "True":
        rate += "$^\\dagger$"
    return head + [
        tex(row["cycles"]),
        "%s/%s" % (tex(row["kept"]), tex(row["runs"])),
        rng(row, "compile_s", 2),
        rng(row, "run_s", 2),
        rng(row, "total_s", 2),
        rate,
        mib(row),
    ]


def table(campaign, lang_name, rows):
    lines = [
        "\\begin{table}[htbp]",
        "\\centering\\scriptsize",
        "\\caption{%s, campaign %s: median [min--max] of the kept runs.}"
        % (lang_name, tex(campaign)),
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{llllrrllllr}",
        "\\hline",
        "Simulator & Design & Case & Cap & Cycles & Kept & Compile (s) & "
        "Run (s) & Total (s) & Cycles/s & Peak RSS (MiB) \\\\",
        "\\hline",
    ]
    for r in rows:
        lines.append(" & ".join(cell_row(r)) + " \\\\")
    lines += ["\\hline", "\\end{tabular}}", "\\end{table}", ""]
    return "\n".join(lines)


def provenance(campaign, rows):
    seen = []
    for r in rows:
        key = (r["git_commit"], r["git_dirty"], r["lock_sha256"])
        if key not in seen:
            seen.append(key)
    parts = [
        "commit \\texttt{%s} (%s), lockfile \\texttt{%s}" % (tex(c), tex(d), tex(l))
        for c, d, l in seen
    ]
    hosts = sorted({r["host"] for r in rows})
    return "\\item Campaign %s, host %s: %s.\n" % (
        tex(campaign), tex(", ".join(hosts)), "; ".join(parts))


def main(argv):
    p = argparse.ArgumentParser()
    p.add_argument("--out", required=True)
    p.add_argument("--provenance", required=True)
    p.add_argument("campaigns", nargs="+", help="<campaign>=<summary.csv>")
    a = p.parse_args(argv)
    tables, prov = [], []
    for spec in a.campaigns:
        name, path = spec.split("=", 1)
        with open(path, newline="") as f:
            rows = list(csv.DictReader(f))
        for key, lang_name in LANGUAGES:
            sub = [r for r in rows if language(r) == key]
            if sub:
                tables.append(table(name, lang_name, sub))
        prov.append(provenance(name, rows))
    with open(a.out, "w") as f:
        f.write("% Generated by //tools:report_tables. Do not edit.\n")
        f.write("\n".join(tables))
    with open(a.provenance, "w") as f:
        f.write("% Generated by //tools:report_tables. Do not edit.\n")
        f.write("\\begin{itemize}\n" + "".join(prov) + "\\end{itemize}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
